export type AlgorithmTone = 'search' | 'data' | 'graph' | 'dp' | 'string' | 'math'
export type AlgorithmKind = 'hub' | 'algorithm' | 'variant'

export interface AlgorithmTopic {
  id: string
  title: string
  category: string
  difficulty: '概览' | '基础' | '进阶'
  tone: AlgorithmTone
  kind: AlgorithmKind
  description: string
  keyPoints: string[]
  url: string
  position: { x: number; y: number }
}

export interface AlgorithmEdge {
  from: string
  to: string
}

function topic(
  id: string,
  title: string,
  category: string,
  tone: AlgorithmTone,
  kind: AlgorithmKind,
  difficulty: AlgorithmTopic['difficulty'],
  description: string,
  keyPoints: string[],
  url: string,
  x: number,
  y: number
): AlgorithmTopic {
  const positionOffset = { x: 250, y: 120 }
  return {
    id,
    title,
    category,
    tone,
    kind,
    difficulty,
    description,
    keyPoints,
    url,
    position: { x: x + positionOffset.x, y: y + positionOffset.y },
  }
}

